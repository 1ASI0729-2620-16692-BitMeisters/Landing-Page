function setLanguage(next, announce = false) {
  language = next === "en" ? "en" : "es";
  document.documentElement.lang = language;
  for (const { node, original, key } of textBindings) {
    node.nodeValue =
      language === "es"
        ? original
        : original.replace(original.trim(), () => EN[key]);
  }
  for (const { el, attr, value } of attributeBindings)
    el.setAttribute(attr, t(value));
  document
    .querySelectorAll("[data-language]")
    .forEach((button) =>
      button.setAttribute(
        "aria-pressed",
        String(button.dataset.language === language),
      ),
    );
  updateMenuLabel();
  updateCount();
  renderInspection();
  if (PLATFORM_URL && /^https:\/\//.test(PLATFORM_URL))
    document.querySelectorAll("[data-app-link]").forEach((link) => {
      link.href = PLATFORM_URL;
      link.firstChild.textContent = t("Ir a la plataforma") + " ";
    });
  try {
    localStorage.setItem("fleetsafe-language", language);
  } catch (_) {}
  if (announce)
    document.querySelector("#language-announcement").textContent =
      language === "en"
        ? "Language changed to English."
        : "Idioma cambiado a español.";
}
